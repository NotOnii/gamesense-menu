// embed.js out.h file... - PNG assets as byte arrays, so the menu ships as one exe (like the original's in-image menuBin)
const fs = require("fs");
const [out, ...files] = process.argv.slice(2);
const L = ["// GENERATED by re/embed.js - embedded PNG assets. Do not edit.",
  "struct EmbeddedAsset { const char* name; const unsigned char* data; unsigned size; };"];
const names = [];
files.forEach((f, i) => {
  const b = fs.readFileSync(f), id = "asset_" + i;
  names.push([f.replace(/\\/g, "/").replace(/^.*assets\//, ""), id, b.length]);
  const rows = [];
  for (let j = 0; j < b.length; j += 24) rows.push("    " + [...b.slice(j, j + 24)].map(x => "0x" + x.toString(16).padStart(2, "0")).join(",") + ",");
  L.push(`static const unsigned char ${id}[] = {\n${rows.join("\n")}\n};`);
});
L.push("static const EmbeddedAsset EMBEDDED_ASSETS[] = {" + names.map(([n, id, s]) => `{"${n}", ${id}, ${s}}`).join(", ") + "};");
fs.writeFileSync(out, L.join("\n") + "\n");
console.log(names.length, "assets");
